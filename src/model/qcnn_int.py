"""Bit-exact integer QCNN: golden model for RTL + parameter/test-vector export.

Fixed-point rules (RTL must match exactly):
  input   uint8, frac bits 8; hidden activations unsigned act_bits (default 8)
  conv    acc = sum(w_int8 * a_in) + b_int32
          a_out = (acc + 2^(sh-1)) >>> sh, sh = f_in + f_w - f_out
          hidden: clamp to [0, act_hi] (= ReLU + unsigned); last: clamp to int16
  gap     (sum + 2^(sh-1)) >>> sh over the 4x4 map (sh = 4)
"""
import json
from pathlib import Path

import numpy as np


def conv2d_int(x, w, b, stride, pad):
    k = w.shape[-1]
    x = np.pad(x, ((0, 0), (0, 0), (pad, pad), (pad, pad)))
    win = np.lib.stride_tricks.sliding_window_view(x, (k, k), axis=(2, 3))[:, :, ::stride, ::stride]
    return np.einsum("nchwij,ocij->nohw", win, w, optimize=True) + b[None, :, None, None]


def round_shift(acc, sh):
    return (acc + (1 << (sh - 1))) >> sh


def forward_int(qmodel, x_u8, keep_layers=False):
    """x_u8: (N, H, W) uint8 -> int16 output (N,), or list of per-layer maps."""
    a, outs = x_u8[:, None].astype(np.int64), []
    for layer in qmodel:
        if layer["type"] == "gap":
            a = round_shift(a.sum((2, 3), keepdims=True), layer["shift"])
        else:
            acc = conv2d_int(a, layer["w"], layer["b"], layer["stride"], layer["pad"])
            a = np.clip(round_shift(acc, layer["shift"]), *((0, layer.get("act_hi", 255)) if layer["relu"] else (-32768, 32767)))
        outs.append(a)
    return outs if keep_layers else a[:, 0, 0, 0]


def predict_int(qmodel, x_u8, batch_size=256):
    return np.concatenate([forward_int(qmodel, x_u8[i:i + batch_size]) for i in range(0, len(x_u8), batch_size)])


def save_qmodel(qmodel, path):
    arrays = {f"l{i}_{k}": layer[k] for i, layer in enumerate(qmodel) for k in ("w", "b") if k in layer}
    meta = [{k: v for k, v in layer.items() if k not in ("w", "b")} for layer in qmodel]
    np.savez(path, meta=json.dumps(meta), **arrays)


def load_qmodel(path):
    data = np.load(path)
    qmodel = json.loads(str(data["meta"]))
    for i, layer in enumerate(qmodel):
        for k in ("w", "b"):
            if f"l{i}_{k}" in data:
                layer[k] = data[f"l{i}_{k}"].astype(np.int64)
    return qmodel


def hex_lines(values, bits):
    mask = (1 << bits) - 1
    return "\n".join(f"{int(v) & mask:0{bits // 4}x}" for v in np.ravel(values)) + "\n"


def export_rtl(qmodel, x_u8, out_dir):
    """Write ROM .mem files, a Verilog header with shifts, and test vectors."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    convs = [layer for layer in qmodel if layer["type"] == "conv"]
    header = ["// Generated by src/model/qcnn_int.py, do not edit",
              f"localparam ACT_BITS = {int(np.log2(convs[0].get('act_hi', 255) + 1))};",
              f"localparam HIDDEN = {convs[-1]['w'].shape[1]};"]
    header += [f"localparam C{i} = {layer['w'].shape[0]};" for i, layer in enumerate(convs[:-2])]
    for i, layer in enumerate(qmodel):
        header.append(f"localparam L{i}_SHIFT = {layer['shift']};")
        if layer["type"] == "conv":
            (out / f"l{i}_weight.mem").write_text(hex_lines(layer["w"], 8))  # order [oc][ic][ky][kx]
            (out / f"l{i}_bias.mem").write_text(hex_lines(layer["b"], 32))
    (out / "qcnn_params.vh").write_text("\n".join(header) + "\n")

    layer_maps = forward_int(qmodel, x_u8, keep_layers=True)
    (out / "tv_input.mem").write_text(hex_lines(x_u8, 8))                     # [frame][y][x]
    (out / "tv_output.mem").write_text(hex_lines(layer_maps[-1][:, 0, 0, 0], 16))
    for i, a in enumerate(layer_maps[:-1]):                                    # frame 0 only, [c][y][x]
        (out / f"tv_frame0_l{i}.mem").write_text(hex_lines(a[0], 16))


if __name__ == "__main__":
    # python src/model/qcnn_int.py <qmodel.npz> <out_dir> [n_frames]: re-export without retraining
    import sys
    data_dir = Path("data/processed/fss_exp_thermal")
    labels = np.load(data_dir / "labels.npz")
    idx = np.flatnonzero(labels["dataset_id"] == 14)[:int(sys.argv[3]) if len(sys.argv) > 3 else 16]
    x = np.load(data_dir / "images.npy", mmap_mode="r")[idx].astype(np.int64)
    x_u8 = ((x.reshape(len(idx), 56, 4, 56, 4).sum((2, 4)) + 8) >> 4).astype(np.uint8)  # same as training pool
    export_rtl(load_qmodel(sys.argv[1]), x_u8, sys.argv[2])
